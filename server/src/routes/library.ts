import { Router } from 'express';
import { listLibrary, getLibraryBook, getLibraryPage, searchLibrary, readingProgress } from '../controllers/libraryController';
import { authMiddleware } from '../middleware/auth';
import {requireSection} from '../middleware/siteFeatures';
import {privateContentHeaders,requireContentAccount,contentPageLimiter,contentMediaLimiter} from '../middleware/contentSecurity';
import {getPageLineMap} from '../controllers/pageLineController';
const router = Router();
router.get('/', listLibrary);
router.get('/search', requireSection('search'),privateContentHeaders,requireContentAccount,contentPageLimiter,searchLibrary);
router.get('/progress',privateContentHeaders, authMiddleware, readingProgress);
router.put('/progress',privateContentHeaders, authMiddleware, readingProgress);
router.get('/:id',privateContentHeaders, getLibraryBook);
router.get('/:id/pages/:page',privateContentHeaders,requireContentAccount,contentPageLimiter,getLibraryPage);
router.get('/:id/pages/:page/line-map',privateContentHeaders,requireContentAccount,contentMediaLimiter,getPageLineMap);
export default router;
